const out: Record<string, string> = {};
for (const name of [...new Set([...HERALDIC, ...UI])]) {
  const icon = data.icons[name];
  if (!icon) throw new Error(`Icon ${name} not found`);
  out[name] = icon.body.replace(/\s*fill="currentColor"/g, '');
}
const header = `/* Generated by tools/icons/extract.ts — do not edit.
 * Icons from game-icons.net by Lorc, Delapouite and contributors, licensed CC BY 3.0
 * (https://creativecommons.org/licenses/by/3.0/). All icons use a 512×512 viewBox. */
`;
writeFileSync(
  'src/assets/icons.ts',
  `${header}export type IconName = ${Object.keys(out)
    .map((n) => `'${n}'`)
    .join(' | ')};\n\nexport const ICONS: Record<IconName, string> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons`);
