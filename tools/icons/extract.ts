import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const file = require.resolve('@iconify-json/game-icons/icons.json');
const data = JSON.parse(readFileSync(file, 'utf8')) as { icons: Record<string, { body: string }> };

